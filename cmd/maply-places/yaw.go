// thumbYaw is the direction a panorama's strip on the days page faces,
// picked from the frame under key and remembered in cache, so a rerun keeps
// the direction a curator may have looked at. A curator's own direction,
// from the facts file, wins.
func (p *preparer) thumbYaw(key, cache string, own *float64) (*float64, error) {
	if own != nil {
		v := normYaw(*own)
		return &v, nil
	}
	if raw, err := os.ReadFile(cache); err == nil {
		v, err := strconv.ParseFloat(strings.TrimSpace(string(raw)), 64)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", cache, err)
		}
		return &v, nil
	}
	img, err := decode(filepath.Join(p.out, "images", key))
	if err != nil {
		return nil, err
	}
	v := thumb.Pick(img)
	return &v, os.WriteFile(cache, []byte(strconv.FormatFloat(v, 'f', -1, 64)), 0o644)
}

func normYaw(v float64) float64 {
	for v < 0 {
		v += 360
	}
	for v >= 360 {
		v -= 360
	}
	return v
}

func decode(path string) (image.Image, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	img, _, err := image.Decode(f)
	if err != nil {
		return nil, fmt.Errorf("decode %s: %w", filepath.Base(path), err)
	}
	return img, nil
}

var keyPattern = regexp.MustCompile(`^[A-Za-z0-9]{8,64}$`)

// thumbYaws picks the strip's direction for the places already in the
// queue. It reads "id,kind,image_key" rows from csvPath (the header is
// skipped), the images from imagesDir, and writes to out an UPDATE per
// panorama, which sets the direction only where none is set yet, and each
// strip to <out>/thumb-yaws/<id>.jpg for a look before the SQL is applied.
//
//	\copy (SELECT id, kind, image_key FROM maply.place WHERE kind = 'panorama' AND thumb_yaw IS NULL ORDER BY id) TO 'places.csv' CSV HEADER
func thumbYaws(csvPath, imagesDir, out string) error {
	f, err := os.Open(csvPath)
	if err != nil {
		return err
	}
	rows, err := csv.NewReader(f).ReadAll()
	f.Close()
	if err != nil {
		return err
	}
	if len(rows) == 0 {
		return fmt.Errorf("%s is empty", csvPath)
	}
	strips := filepath.Join(out, "thumb-yaws")
	if err := os.MkdirAll(strips, 0o755); err != nil {
		return err
	}
	var sql bytes.Buffer
	sql.WriteString("-- Generated by cmd/maply-places -thumb-yaws. Sets the days page's strip\n-- direction where none is set; a rerun changes nothing.\nBEGIN;\n")
	n := 0
	for _, r := range rows[1:] {
		if len(r) != 3 || r[1] != "panorama" {
			continue
		}
		id, kind, key := r[0], r[1], r[2]
		if _, err := strconv.ParseInt(id, 10, 64); err != nil || !keyPattern.MatchString(key) {
			log.Printf("row %q: skipped", strings.Join(r, ","))
			continue
		}
		img, err := decode(filepath.Join(imagesDir, key))
		if err != nil {
			log.Printf("place %s: %v", id, err)
			continue
		}
		if !thumb.Pano(img) {
			log.Printf("place %s: a %s that is not 2:1, left to the crop", id, kind)
			continue
		}
		yaw := thumb.Pick(img)
		data, err := thumb.JPEG(thumb.Frame(img, yaw, thumb.Small), thumb.Small)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(strips, id+".jpg"), data, 0o644); err != nil {
			return err
		}
		fmt.Fprintf(&sql, "UPDATE maply.place SET thumb_yaw = %s WHERE id = %s AND image_key = %s AND thumb_yaw IS NULL;\n",
			strconv.FormatFloat(yaw, 'f', -1, 64), id, lit(key))
		n++
	}
	sql.WriteString("COMMIT;\n")
	path := filepath.Join(out, "thumb-yaws.sql")
	if err := os.WriteFile(path, sql.Bytes(), 0o644); err != nil {
		return err
	}
	log.Printf("%d directions in %s, their strips in %s", n, path, strips)
	return nil
}
