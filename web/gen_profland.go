// gen_profland writes app/profland.js: the land dots of the profile's map,
// each with its country, so the passport colours the countries a player
// found and the map of pins needs no tiles. The dots sit in rows along the
// parallels as in gen_land.go; the file carries the number of dots in each
// row, one bit per dot for land, and for every land dot in order one byte:
// its country's place in the list of codes plus one, zero for none. A
// country too small to hold a dot of the grid gets one extra dot inside it,
// so the passport can colour it too.
//
//	go run gen_profland.go -step 2 -o app/profland.js
package main

import (
	"compress/gzip"
	"encoding/base64"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"math"
	"os"
	"slices"
	"strings"

	"github.com/FreshLabDev/maply/internal/geo"
)

func main() {
	step := flag.Float64("step", 2, "degrees between rows and between dots in a row")
	out := flag.String("o", "app/profland.js", "output file")
	flag.Parse()

	world, err := geo.World()
	if err != nil {
		log.Fatal(err)
	}
	var (
		rows []string
		bits []byte
		land []string
	)
	n := 0
	for i, lat := 0, -90+*step/2; lat < 90; i, lat = i+1, lat+*step {
		count := max(1, int(math.Round(360*math.Cos(lat*math.Pi/180) / *step)))
		rows = append(rows, fmt.Sprint(count))
		for j := 0; j < count; j++ {
			lon := -180 + (float64(j)+0.5+float64(i%2)*0.5)*360/float64(count)
			if lon >= 180 {
				lon -= 360
			}
			if n%8 == 0 {
				bits = append(bits, 0)
			}
			if c, ok := world.Locate(geo.Point{Lat: lat, Lon: lon}); ok {
				bits[n/8] |= 1 << (n % 8)
				land = append(land, c.ISO)
			}
			n++
		}
	}
	extra := smallCountries(world, land)
	codes := slices.Clone(land)
	for _, e := range extra {
		codes = append(codes, e.iso)
	}
	slices.Sort(codes)
	codes = slices.Compact(codes)
	if len(codes) > 254 {
		log.Fatalf("%d countries do not fit a byte", len(codes))
	}
	idx := make([]byte, len(land))
	for i, iso := range land {
		k, _ := slices.BinarySearch(codes, iso)
		idx[i] = byte(k + 1)
	}
	list, _ := json.Marshal(codes)
	var more []string
	for _, e := range extra {
		k, _ := slices.BinarySearch(codes, e.iso)
		more = append(more, fmt.Sprintf("[%.2f,%.2f,%d]", e.lon, e.lat, k+1))
	}
	js := fmt.Sprintf("// Generated by gen_profland.go: the land dots of the profile's map, with their countries. Do not edit.\n"+
		"const PROFILE_LAND = { step: %g, rows: [%s], bits: %q, codes: %s, land: %q, extra: [%s] };\n",
		*step, strings.Join(rows, ","), base64.StdEncoding.EncodeToString(bits), list, base64.StdEncoding.EncodeToString(idx), strings.Join(more, ","))
	if err := os.WriteFile(*out, []byte(js), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d dots, %d on land, %d extra, %d countries, %d bytes", n, len(land), len(extra), len(codes), len(js))
}

type dot struct {
	iso      string
	lon, lat float64
}

// smallCountries is one dot for each country no dot of the grid fell in: the
// point of a fine grid over its bounds nearest the middle of its points.
func smallCountries(world *geo.Countries, land []string) []dot {
	f, err := os.Open("../internal/geo/countries.geojson.gz")
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	gz, err := gzip.NewReader(f)
	if err != nil {
		log.Fatal(err)
	}
	var fc struct {
		Features []struct {
			Properties struct {
				ISO string `json:"iso"`
			} `json:"properties"`
			Geometry struct {
				Coordinates json.RawMessage `json:"coordinates"`
			} `json:"geometry"`
		} `json:"features"`
	}
	if err := json.NewDecoder(gz).Decode(&fc); err != nil {
		log.Fatal(err)
	}
	have := map[string]bool{}
	for _, iso := range land {
		have[iso] = true
	}
	var out []dot
	for _, ft := range fc.Features {
		iso := ft.Properties.ISO
		if have[iso] {
			continue
		}
		have[iso] = true
		// Every number pair in the coordinates, however deeply nested.
		var nums []float64
		collect(ft.Geometry.Coordinates, &nums)
		w, e, s, n := 180.0, -180.0, 90.0, -90.0
		for i := 0; i+1 < len(nums); i += 2 {
			w, e = min(w, nums[i]), max(e, nums[i])
			s, n = min(s, nums[i+1]), max(n, nums[i+1])
		}
		// Across the antimeridian the bounds would be the whole world.
		if e-w > 90 {
			continue
		}
		const fine = 0.05
		var in []dot
		for lat := s; lat <= n; lat += fine {
			for lon := w; lon <= e; lon += fine {
				if c, ok := world.Locate(geo.Point{Lat: lat, Lon: lon}); ok && c.ISO == iso {
					in = append(in, dot{iso, lon, lat})
				}
			}
		}
		if len(in) == 0 {
			log.Printf("%s: no point found", iso)
			continue
		}
		var mlon, mlat float64
		for _, d := range in {
			mlon += d.lon / float64(len(in))
			mlat += d.lat / float64(len(in))
		}
		best := in[0]
		for _, d := range in[1:] {
			if math.Hypot(d.lon-mlon, d.lat-mlat) < math.Hypot(best.lon-mlon, best.lat-mlat) {
				best = d
			}
		}
		out = append(out, best)
	}
	slices.SortFunc(out, func(a, b dot) int { return strings.Compare(a.iso, b.iso) })
	return out
}

func collect(raw json.RawMessage, nums *[]float64) {
	var arr []json.RawMessage
	if err := json.Unmarshal(raw, &arr); err != nil {
		return
	}
	if len(arr) >= 2 {
		var x, y float64
		if json.Unmarshal(arr[0], &x) == nil && json.Unmarshal(arr[1], &y) == nil {
			*nums = append(*nums, x, y)
			return
		}
	}
	for _, a := range arr {
		collect(a, nums)
	}
}
