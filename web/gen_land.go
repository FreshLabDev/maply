// gen_land writes app/land.js: which dots of the loading screen's globe are
// land. The dots sit in rows along the parallels, step degrees apart, every
// other row shifted by half a dot; the file carries the number of dots in each
// row and one bit per dot, so the page draws the globe without a map.
//
//	go run gen_land.go -step 4 -o app/land.js
package main

import (
	"encoding/base64"
	"flag"
	"fmt"
	"log"
	"math"
	"os"
	"strings"

	"github.com/FreshLabDev/maply/internal/geo"
)

func main() {
	step := flag.Float64("step", 4, "degrees between rows and between dots in a row")
	out := flag.String("o", "app/land.js", "output file")
	flag.Parse()

	world, err := geo.World()
	if err != nil {
		log.Fatal(err)
	}
	var rows []string
	var bits []byte
	n := 0
	for i, lat := 0, -90+*step/2; lat < 90; i, lat = i+1, lat+*step {
		count := max(1, int(math.Round(360*math.Cos(lat*math.Pi/180) / *step)))
		rows = append(rows, fmt.Sprint(count))
		for j := 0; j < count; j++ {
			lon := -180 + (float64(j)+0.5+float64(i%2)*0.5)*360/float64(count)
			if lon >= 180 {
				lon -= 360
			}
			if n%8 == 0 {
				bits = append(bits, 0)
			}
			if _, ok := world.Locate(geo.Point{Lat: lat, Lon: lon}); ok {
				bits[n/8] |= 1 << (n % 8)
			}
			n++
		}
	}
	js := fmt.Sprintf("// Generated by gen_land.go: the land dots of the loading screen's globe. Do not edit.\n"+
		"const LAND = { step: %g, rows: [%s], bits: %q };\n", *step, strings.Join(rows, ","), base64.StdEncoding.EncodeToString(bits))
	if err := os.WriteFile(*out, []byte(js), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d dots, %d bytes", n, len(js))
}
